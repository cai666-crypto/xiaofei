def cn_to_int(text: str):
    """把「三百」「一千五」这类中文数字转成整数。"""
    total, current = 0, 0
    for ch in text:
        if ch in CN_DIGITS:
            current = CN_DIGITS[ch]
        elif ch in CN_UNITS:
            unit = CN_UNITS[ch]
            if current == 0:
                current = 1
            total += current * unit
            current = 0
        else:
            return None
    # 口语补位：「一千五」= 1500、「三百五」= 350
    if text and text[-1] in CN_DIGITS and len(text) >= 2:
        prev_unit = CN_UNITS.get(text[-2])
        if prev_unit in (100, 1000) and current < 10:
            total += current * (prev_unit // 10)
            current = 0
    return total + current


def parse_budget(text: str):
    """从自然语言里抽出预算区间，返回 (min, max)。"""
    t = text.replace(" ", "")
    has_range = bool(
        re.search(r"\d+\s*[-~到至]\s*\d+", t)
        or re.search(r"[百千]\s*[到至]\s*[一二两三四五六七八九十百千]", t)
    )
    if not has_range and not any(k in t for k in BUDGET_HINTS):
        return None, None

    numbers = [int(n) for n in re.findall(r"\d+", t)]
    for m in re.finditer(r"[零一二两三四五六七八九十百千]{1,6}", t):
        val = cn_to_int(m.group(0))
        if val and 30 <= val <= 20000:          # 过滤「一起」「两个」这类误命中
            numbers.append(val)

    numbers = sorted(set(numbers))
    if not numbers:
        return None, None

    # 区间写法：300-500 / 三百到五百
    if len(numbers) >= 2 and re.search(r"\d+\s*[-~到至]\s*\d+|[百千]\s*[到至]\s*[一二两三四五六七八九十百千]", t):
        return numbers[0], numbers[-1]

    if "以上" in t or "起步" in t:
        return numbers[0], None
    return None, numbers[0]


