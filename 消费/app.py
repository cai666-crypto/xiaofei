def init_state():
    ss = st.session_state
    ss.setdefault("messages", [])
    ss.setdefault("profile", {})
    ss.setdefault("picked", [])
    ss.setdefault("copies", [])
    ss.setdefault("pending", None)
    ss.setdefault("turn", 0)
    if not ss.messages:
        ss.messages.append({"role": "assistant", "content": WELCOME, "products": []})


def update_profile(intent):
    """把本轮识别出的关注点沉淀成用户偏好。"""
    for tag in intent["terms"]:
        st.session_state.profile[tag] = st.session_state.profile.get(tag, 0) + 1
    for cat in intent["cats"]:
        st.session_state.profile[cat] = st.session_state.profile.get(cat, 0) + 1.5


def handle_query(text):
    intent = parse_intent(text)
    items = recommend(intent)
    reply = build_reply(intent, items)
    st.session_state.messages.append({"role": "user", "content": text})
    st.session_state.messages.append({
        "role": "assistant",
        "content": reply,
        "products": [p["id"] for p, _ in items],
        "reasons": {p["id"]: r for p, r in items},
        "intent": intent,
    })
    update_profile(intent)
    st.session_state.turn += 1


