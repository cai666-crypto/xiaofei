def render_product_card(p, reasons, turn, col_idx):
    with st.container(border=True):
        st.markdown(f"**{p['emoji']} {p['name']}**")
        meta = p["brand"]
        if p.get("platform"):
            meta += f" · {p['platform']}"
        meta += f" · ⭐ {p['rating']}"
        st.caption(meta)
        st.markdown(
            f"<div class='price'>¥{p['price']}<small>/{p['sub']}</small></div>",
            unsafe_allow_html=True,
        )
        pills = "".join(f"<span class='pill'>{t}</span>" for t in p["tags"])
        st.markdown(pills, unsafe_allow_html=True)

        pros = p.get("pros") or p["points"][:2]
        cons = p.get("cons") or []
        rows = "".join(f"<div class='pro'>✓ {x}</div>" for x in pros[:3])
        rows += "".join(f"<div class='con'>✕ {x}</div>" for x in cons[:2])
        st.markdown(rows, unsafe_allow_html=True)

        if reasons:
            st.markdown(
                f"<div style='font-size:12px;color:#E8537D;margin-top:8px'>🎯 {'，'.join(reasons)}</div>",
                unsafe_allow_html=True,
            )

        key = f"pick_{turn}_{col_idx}_{p['id']}"
        if p["id"] in st.session_state.picked:
            st.button("✅ 已选中", key=key, disabled=True, use_container_width=True)
        else:
            if st.button("✨ 选它 · 生成文案", key=key, use_container_width=True, type="primary"):
                st.session_state.picked.append(p["id"])
                st.session_state.copies.insert(0, make_copy(p["id"]))
                st.toast(f"已加入清单：{p['name']}，文案已生成 ✍️")
                st.rerun()


def render_card_row(ids, reasons, turn, tag):
    """按每行最多 3 张卡片铺开。"""
    for row in range(0, len(ids), 3):
        chunk = ids[row:row + 3]
        cols = st.columns(len(chunk), gap="small")
        for j, (c, pid) in enumerate(zip(cols, chunk)):
            with c:
                render_product_card(
                    PRODUCT_BY_ID[pid], reasons.get(pid, []), turn, f"{tag}{row + j}"
                )


def render_message(msg, idx):
    if msg["role"] == "user":
        with st.chat_message("user", avatar="🙋"):
            st.markdown(msg["content"])
        return

    with st.chat_message("assistant", avatar="🛍️"):
        st.markdown(msg["content"])
        if msg.get("products"):
            render_card_row(msg["products"], msg.get("reasons", {}), idx, "m")


