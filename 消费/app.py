def score_product(product, intent):
    score = product["rating"] * 4.0        # 基础分：口碑
    reasons = []

    if intent["cats"]:
        if product["cat"] in intent["cats"]:
            score += 45
            reasons.append(f"品类正好是{product['cat']}")
        else:
            score -= 28

    if intent.get("persona") and product["cat"] in intent["persona"]:
        score += 12
        reasons.append("符合你提到的人群")

    if intent["subs"]:
        if product["sub"] in intent["subs"]:
            score += 22
            reasons.append(f"你要的就是{product['sub']}")
        else:
            score -= 8

    tag_hits = [t for t in product["tags"] if t in intent["terms"]]
    if tag_hits:
        score += len(tag_hits) * 14
        reasons.append("、".join(f"「{t}」" for t in tag_hits[:3]) + "都踩中")

    bmax, bmin = intent["budget_max"], intent["budget_min"]
    if bmax is not None:
        if product["price"] <= bmax:
            if bmin is not None and product["price"] < bmin:
                reasons.append(f"¥{product['price']} 比你说的价位更划算")
            else:
                score += 18
                reasons.append(f"¥{product['price']} 在预算内")
        else:
            score -= 30

    # 价格偏好微调：说「性价比/便宜」偏向低价，说「高端/品质」偏向高价
    if {"平价", "便宜"} & intent["terms"]:
        score += max(0, (200 - product["price"]) / 20)
    if {"品质", "质感"} & intent["terms"]:
        score += product["price"] / 40

    return score, reasons


def budget_guard(items, bmax):
    """【硬性规则】预算上限守卫：任何情况下都不输出价格超预算的商品。"""
    if bmax is None:
        return list(items)
    return [(p, r) for p, r in items if p["price"] <= bmax]


