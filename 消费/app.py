def scene_line(p):
    if p["sub"] in SUB_SCENES:
        return random.choice(SUB_SCENES[p["sub"]])
    return random.choice(SCENE_LINES[p["cat"]])


OPENERS = ["姐妹们！！", "宝子们听我说，", "真的忍不住了，", "不许还有人不知道，"]
ENDINGS = ["闭眼冲就完事了", "我已经回购第二次了", "链接放这了，冲", "谁用谁知道🫶"]
EMOJIS = ["✨", "🔥", "💯", "🥹", "🫶", "💗", "😭"]


def price_line(price):
    for limit, text in PRICE_LINES:
        if price < limit:
            return text.format(price=price)
    return f"{price} 块"


def topic_tags(p):
    tags = [p["brand"].replace(" ", ""), p["cat"], p["sub"]] + p["tags"][:2]
    seen, out = set(), []
    for t in tags:
        if t and t not in seen:
            seen.add(t)
            out.append("#" + t)
    return " ".join(out)


